'use strict';

const fs = require('fs');
const http = require('http');
const path = require('path');

// Maps file extensions to standard HTTP Content-Type headers for local previewing.
const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8'
};

// Creates a minimal, sandboxed HTTP server that serves static files from webDir.
// Disables browser caching so live edits appear immediately on refresh.
function createStaticServer(webDir, safePath) {
  return http.createServer((req, res) => {
    // Allow only safe, read-only HTTP methods for a local static preview server.
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      res.writeHead(405, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end('Method Not Allowed');
      return;
    }

    // Strip query parameters and decode the URL path safely.
    let requestPath;
    try {
      const rawUrlPath = (req.url || '/').split('?')[0];
      requestPath = decodeURIComponent(rawUrlPath);
    } catch {
      res.writeHead(400, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end('Bad Request');
      return;
    }

    // Resolve the requested URL inside webDir and block any directory traversal attempt.
    let targetPath;
    try {
      const relativeUrlPath = requestPath.replace(/^\/+/, '');
      targetPath = safePath(webDir, relativeUrlPath || 'index.html');
    } catch {
      res.writeHead(403, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end('Forbidden');
      return;
    }

    // Serve index.html automatically when the request points to a directory.
    if (fs.existsSync(targetPath) && fs.statSync(targetPath).isDirectory()) {
      targetPath = path.join(targetPath, 'index.html');
    }

    if (!fs.existsSync(targetPath) || !fs.statSync(targetPath).isFile()) {
      res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end('404 Not Found');
      return;
    }

    const extension = path.extname(targetPath).toLowerCase();
    const contentType = MIME_TYPES[extension] || 'application/octet-stream';

    res.writeHead(200, {
      'Content-Type': contentType,
      'Cache-Control': 'no-store',
      'X-Content-Type-Options': 'nosniff'
    });

    if (req.method === 'HEAD') {
      res.end();
      return;
    }

    const stream = fs.createReadStream(targetPath);
    stream.on('error', () => {
      if (!res.headersSent) {
        res.writeHead(500, { 'Content-Type': 'text/plain; charset=utf-8' });
      }
      res.end('Internal Server Error');
    });
    stream.pipe(res);
  });
}

// Builds a map of directories to watch alongside a predicate describing which filenames matter.
// Watching parent directories instead of individual files stays reliable when editors perform atomic saves.
function collectWatchMap(config, configPath) {
  const watchMap = new Map();

  // Registers a single filename or wildcard marker ("*.md") under its parent directory.
  function registerTarget(dirPath, rule) {
    if (!fs.existsSync(dirPath)) {
      return;
    }
    if (!watchMap.has(dirPath)) {
      watchMap.set(dirPath, new Set());
    }
    watchMap.get(dirPath).add(rule);
  }

  registerTarget(path.dirname(configPath), path.basename(configPath));

  for (const section of config.sections) {
    registerTarget(section.srcDir, '*.md');
    registerTarget(path.dirname(section.template), path.basename(section.template));
  }

  for (const extensionPath of config.extensions) {
    registerTarget(path.dirname(extensionPath), path.basename(extensionPath));
  }

  return watchMap;
}

// Checks whether a filesystem event filename matches any registered watch rule for its directory.
function matchesWatchRules(filename, rules) {
  if (!filename) {
    return false;
  }

  // Ignore temporary swap and backup files generated by text editors.
  if (filename.startsWith('.') || filename.endsWith('~') || filename.endsWith('.tmp') || filename.endsWith('.swp')) {
    return false;
  }

  if (rules.has(filename)) {
    return true;
  }

  return rules.has('*.md') && filename.endsWith('.md');
}

// Prints the live-mode status header and available keyboard shortcuts cleanly.
function printLiveBanner(host, port) {
  console.log(`\nLive server running at http://${host}:${port}`);
  console.log('Watching Markdown files, templates, extensions, and build-config.js.');
  console.log('Controls: [r] rebuild  [c] clear  [q] quit\n');
}

// Starts the local HTTP server, native file watchers, and guarded keyboard controls.
function startLiveMode({ config, configPath, onRebuild, safePath }) {
  const { host, port } = config.server;
  const server = createStaticServer(config.webDir, safePath);
  const watchers = [];

  let debounceTimer = null;
  let isBuilding = false;
  let hasQueuedBuild = false;
  let isShuttingDown = false;

  // Executes a rebuild safely while preventing overlapping builds during rapid file saves.
  function triggerRebuild(reason) {
    if (isBuilding) {
      hasQueuedBuild = true;
      return;
    }

    isBuilding = true;
    console.log(`\nChange detected (${reason}). Rebuilding...`);

    try {
      onRebuild();
    } catch (error) {
      console.error(`Build failed: ${error.message}`);
    } finally {
      isBuilding = false;
      if (hasQueuedBuild) {
        hasQueuedBuild = false;
        triggerRebuild('queued changes');
      }
    }
  }

  // Schedules a debounced rebuild so multiple OS write events coalesce into one build.
  function scheduleRebuild(reason) {
    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => triggerRebuild(reason), 200);
  }

  // Closes all watchers, stops the HTTP server, and restores terminal input state cleanly.
  function shutdown() {
    if (isShuttingDown) {
      return;
    }
    isShuttingDown = true;

    clearTimeout(debounceTimer);

    for (const watcher of watchers) {
      watcher.close();
    }

    if (process.stdin.isTTY) {
      process.stdin.setRawMode(false);
      process.stdin.pause();
    }

    server.close(() => {
      console.log('\nLive server stopped.');
      process.exit(0);
    });

    // Force exit quickly if an open browser keep-alive connection delays server.close().
    setTimeout(() => process.exit(0), 500).unref();
  }

  // Start the HTTP server and surface common binding errors without a stack trace.
  server.on('error', (error) => {
    if (error.code === 'EADDRINUSE') {
      console.error(`Error: Port ${port} on ${host} is already in use.`);
    } else {
      console.error(`Server error: ${error.message}`);
    }
    shutdown();
  });

  server.listen(port, host, () => {
    printLiveBanner(host, port);
  });

  // Attach native directory watchers for all configured inputs.
  const watchMap = collectWatchMap(config, configPath);

  for (const [dirPath, rules] of watchMap.entries()) {
    try {
      const watcher = fs.watch(dirPath, { persistent: true }, (_eventType, filename) => {
        if (matchesWatchRules(filename, rules)) {
          scheduleRebuild(filename);
        }
      });

      watcher.on('error', (error) => {
        console.warn(`Watcher warning (${path.basename(dirPath)}): ${error.message}`);
      });

      watchers.push(watcher);
    } catch (error) {
      console.warn(`Could not watch directory "${dirPath}": ${error.message}`);
    }
  }

  // Guard keyboard input in interactive terminals so stray keystrokes are silently ignored.
  if (process.stdin.isTTY) {
    process.stdin.setRawMode(true);
    process.stdin.resume();
    process.stdin.setEncoding('utf8');

    process.stdin.on('data', (key) => {
      const normalizedKey = key.toLowerCase();

      if (key === '\u0003' || normalizedKey === 'q') {
        shutdown();
      } else if (normalizedKey === 'r') {
        triggerRebuild('manual trigger');
      } else if (normalizedKey === 'c') {
        console.clear();
        printLiveBanner(host, port);
      }
    });
  }

  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

module.exports = { startLiveMode };
